@Composable
fun MainSettingsScreen(
    onClickAbout: () -> Unit,
    onClickTextCorrection: () -> Unit,
    onClickPreferences: () -> Unit,
    onClickToolbar: () -> Unit,
    onClickGestureTyping: () -> Unit,
    onClickDataGathering: () -> Unit,
    onClickAdvanced: () -> Unit,
    onClickAppearance: () -> Unit,
    onClickLanguage: () -> Unit,
    onClickLayouts: () -> Unit,
    onClickDictionaries: () -> Unit,
    onClickBack: () -> Unit,
) {
    val context = LocalContext.current
    val geminiPrefs = remember(context) {
        context.getSharedPreferences("gemini_heliboard", Context.MODE_PRIVATE)
    }
    var showGeminiDialog by remember { mutableStateOf(false) }
    var savedApiKey by remember {
        mutableStateOf(geminiPrefs.getString("api_key", "").orEmpty())
    }
    var stripEnabled by remember {
        mutableStateOf(geminiPrefs.getBoolean("strip_enabled", true))
    }

    val geminiStatus = buildString {
        if (savedApiKey.length > 10) {
            append("API Key: ")
            append(savedApiKey.take(6))
            append("...")
            append(savedApiKey.takeLast(4))
        } else {
            append("API Key belum diatur")
        }
        append(if (stripEnabled) " • Bilah aktif" else " • Bilah disembunyikan")
    }

    if (showGeminiDialog) {
        var apiKeyInput by remember(showGeminiDialog) { mutableStateOf(savedApiKey) }
        var stripEnabledInput by remember(showGeminiDialog) { mutableStateOf(stripEnabled) }

        AlertDialog(
            onDismissRequest = { showGeminiDialog = false },
            title = { Text("Pengaturan Gemini AI") },
            text = {
                Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                    OutlinedTextField(
                        value = apiKeyInput,
                        onValueChange = { apiKeyInput = it },
                        label = { Text("Gemini API Key") },
                        placeholder = { Text("Tempel AIza... di sini") },
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth()
                    )
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Text(
                            text = "Tampilkan bilah Gemini di keyboard",
                            modifier = Modifier.weight(1f)
                        )
                        Switch(
                            checked = stripEnabledInput,
                            onCheckedChange = { stripEnabledInput = it }
                        )
                    }
                }
            },
            confirmButton = {
                TextButton(onClick = {
                    val cleanedKey = apiKeyInput.trim()
                    geminiPrefs.edit()
                        .putString("api_key", cleanedKey)
                        .putBoolean("strip_enabled", stripEnabledInput)
                        .apply()
                    savedApiKey = cleanedKey
                    stripEnabled = stripEnabledInput
                    showGeminiDialog = false
                    Toast.makeText(
                        context,
                        if (cleanedKey.isNotEmpty()) "API Key & pengaturan Gemini tersimpan!" else "Pengaturan Gemini tersimpan",
                        Toast.LENGTH_SHORT
                    ).show()
                }) {
                    Text("Simpan")
                }
            },
            dismissButton = {
                TextButton(onClick = { showGeminiDialog = false }) {
                    Text("Batal")
                }
            }
        )
    }

    SearchSettingsScreen(
        onClickBack = onClickBack,
        title = stringResource(R.string.ime_settings),
        settings = emptyList(),
    ) {
        val enabledSubtypes = SubtypeSettings.getEnabledSubtypes(true)
        Scaffold(contentWindowInsets = WindowInsets.safeDrawing.only(WindowInsetsSides.Bottom)) { innerPadding ->
            Column(
                Modifier.verticalScroll(rememberScrollState()).then(Modifier.padding(innerPadding))
            ) {
                Preference(
                    name = "✨ Gemini AI",
                    description = geminiStatus,
                    onClick = { showGeminiDialog = true },
                    icon = R.drawable.ic_settings_advanced
                ) { NextScreenIcon() }
                Preference(
                    name = stringResource(R.string.language_and_layouts_title),
                    description = enabledSubtypes.joinToString(", ") { it.displayName() },
                    onClick = onClickLanguage,
                    icon = R.drawable.ic_settings_languages
                ) { NextScreenIcon() }
                Preference(
                    name = stringResource(R.string.settings_screen_preferences),
                    onClick = onClickPreferences,
                    icon = R.drawable.ic_settings_preferences
                ) { NextScreenIcon() }
                Preference(
                    name = stringResource(R.string.settings_screen_appearance),
                    onClick = onClickAppearance,
                    icon = R.drawable.ic_settings_appearance
                ) { NextScreenIcon() }
                Preference(
                    name = stringResource(R.string.settings_screen_toolbar),
                    onClick = onClickToolbar,
                    icon = R.drawable.ic_settings_toolbar
                ) { NextScreenIcon() }
                if (JniUtils.sHaveGestureLib)
                    Preference(
                        name = stringResource(R.string.settings_screen_gesture),
                        onClick = onClickGestureTyping,
                        icon = R.drawable.ic_settings_gesture
                    ) { NextScreenIcon() }
                // we don't even show the menu if data gathering phase ended more than 2 weeks ago
                if (JniUtils.sHaveGestureLib && System.currentTimeMillis() < END_DATE_EPOCH_MILLIS + TWO_WEEKS_IN_MILLIS)
                    Preference(
                        name = stringResource(R.string.gesture_data_screen),
                        onClick = onClickDataGathering,
                        icon = R.drawable.ic_settings_gesture
                    ) { NextScreenIcon() }
                Preference(
                    name = stringResource(R.string.settings_screen_correction),
                    onClick = onClickTextCorrection,
                    icon = R.drawable.ic_settings_correction
                ) { NextScreenIcon() }
                Preference(
                    name = stringResource(R.string.settings_screen_secondary_layouts),
                    onClick = onClickLayouts,
                    icon = R.drawable.ic_settings_layout
                ) { NextScreenIcon() }
                Preference(
                    name = stringResource(R.string.dictionary_settings_category),
                    onClick = onClickDictionaries,
                    icon = R.drawable.ic_dictionary
                ) { NextScreenIcon() }
                Preference(
                    name = stringResource(R.string.settings_screen_advanced),
                    onClick = onClickAdvanced,
                    icon = R.drawable.ic_settings_advanced
                ) { NextScreenIcon() }
                Preference(
                    name = stringResource(R.string.settings_screen_about),
                    onClick = onClickAbout,
                    icon = R.drawable.ic_settings_about
                ) { NextScreenIcon() }
            }
        }
    }
}

